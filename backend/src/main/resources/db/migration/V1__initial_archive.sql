create table contributions (
  id bigint generated by default as identity primary key,
  collection_slug varchar(50) not null references collections,
  name varchar(150) not null,
  email varchar(254) not null,
  title varchar(180) not null,
  material_type varchar(80) not null,
  description varchar(6000) not null,
  period varchar(150) not null,
  place varchar(180) not null,
  source varchar(500) not null,
  consent boolean not null check (consent = true),
  status varchar(20) not null default 'PENDING' check (status in ('PENDING','APPROVED','REJECTED')),
  created_at timestamp with time zone not null default current_timestamp,
  reviewed_at timestamp with time zone,
  reviewed_by varchar(150),
  related_memory bigint
);

create table memories (
  id bigint generated by default as identity primary key,
  contribution_id bigint not null unique references contributions,
  collection_slug varchar(50) not null references collections,
  title varchar(180) not null,
  material_type varchar(80) not null,
  category varchar(100) not null,
  description varchar(6000) not null,
  period varchar(150) not null,
  historical_year integer check (historical_year between 1 and 2200),
  place varchar(180) not null,
  source varchar(500) not null,
  credits varchar(250) not null,
  usage_terms varchar(500) not null,
  latitude double precision check (latitude between -90 and 90),
  longitude double precision check (longitude between -180 and 180),
  published_at timestamp with time zone not null default current_timestamp,
  check ((latitude is null) = (longitude is null))
);
alter table contributions add constraint contribution_related_memory foreign key (related_memory) references memories;
create index memory_collection on memories(collection_slug);
create index memory_year on memories(historical_year);
create index memory_published on memories(published_at);

create table memory_files (
  id bigint generated by default as identity primary key,
  contribution_id bigint not null references contributions,
  storage_key varchar(80) not null unique,
  file_name varchar(240) not null,
  content_type varchar(100) not null
);
create index file_contribution on memory_files(contribution_id);
