create table record_options (
  id bigint generated by default as identity primary key,
  kind varchar(6) not null check (kind in ('PLACE', 'SOURCE')),
  value varchar(500) not null check (value = trim(value) and value <> ''),
  check (kind <> 'PLACE' or length(value) <= 180)
);

create unique index record_options_kind_value on record_options (kind, lower(value));

-- Preserve the existing suggestions when upgrading to the managed lists.
insert into record_options (kind, value)
select kind, min(value)
from (
  select 'PLACE' as kind, trim(place) as value from memories
  union all
  select 'SOURCE' as kind, trim(source) as value from memories
  union all
  select 'PLACE' as kind, trim(place) as value from contributions where status = 'PENDING'
  union all
  select 'SOURCE' as kind, trim(source) as value from contributions where status = 'PENDING'
) existing
where value <> ''
group by kind, lower(value);
